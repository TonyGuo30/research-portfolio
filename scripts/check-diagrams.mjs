import assert from 'node:assert/strict';
import {diagramIds,diagramDefaults,updateDiagram,diagramView,renderSystemDiagram} from '../dist/system-diagrams.js';
for(const id of diagramIds){
  const initial=diagramDefaults(id);
  const untouched=structuredClone(initial);
  const reset=updateDiagram(id,initial,'reset');
  assert.deepEqual(reset,untouched);
  assert.notEqual(reset,initial);
  assert.ok(renderSystemDiagram(id).includes(diagramView(id,initial).status));
}
let s=updateDiagram('parallax',diagramDefaults('parallax'),'step',3);
assert.match(diagramView('parallax',s).status,/Ground the continuation/);
s=updateDiagram('parallax',s,'gap');
assert.match(diagramView('parallax',s).status,/Ask for clarification/);
let p=diagramDefaults('prediction-to-execution');
assert.equal(diagramView('prediction-to-execution',p).result,396);
const wider=updateDiagram('prediction-to-execution',p,'width',80);
assert.ok(diagramView('prediction-to-execution',wider).result<396);
assert.equal(p.width,40,'Updates must not mutate the starting example');
assert.equal(diagramView('prediction-to-execution',updateDiagram('prediction-to-execution',p,'missing')).result,null);
let canvas=diagramDefaults('enactivecanvas');
canvas=updateDiagram('enactivecanvas',canvas,'note',0);
canvas=updateDiagram('enactivecanvas',canvas,'note',1);
assert.match(diagramView('enactivecanvas',canvas).status,/Choose at least one/);
assert.match(diagramView('enactivecanvas',updateDiagram('enactivecanvas',canvas,'note',2)).description,/low attention/);
let agents=diagramDefaults('virt-lab');
for(let i=0;i<5;i++)agents=updateDiagram('virt-lab',agents,'tick');
assert.equal(agents.tick,3);
assert.match(diagramView('virt-lab',agents).status,/Both task locations reached/);
agents=updateDiagram('virt-lab',agents,'coordinate');
assert.equal(agents.tick,0);
for(let i=0;i<3;i++)agents=updateDiagram('virt-lab',agents,'tick');
assert.match(diagramView('virt-lab',agents).status,/Task B remains unattended/);
const rag=diagramDefaults('hidden-in-plain-text');
assert.match(diagramView('hidden-in-plain-text',rag).status,/excluded/);
assert.match(diagramView('hidden-in-plain-text',updateDiagram('hidden-in-plain-text',rag,'gate')).status,/crosses/);
assert.match(diagramView('hidden-in-plain-text',updateDiagram('hidden-in-plain-text',rag,'injection')).status,/Factual evidence/);
let consent=diagramDefaults('consentdiff');
assert.match(diagramView('consentdiff',consent).status,/2-step/);
consent=updateDiagram('consentdiff',consent,'settings');
assert.match(diagramView('consentdiff',consent).visual,/Reject optional cookies/);
consent=updateDiagram('consentdiff',consent,'reject');
assert.match(diagramView('consentdiff',consent).visual,/Optional cookies rejected/);
consent=updateDiagram('consentdiff',consent,'month',2);
assert.equal(consent.screen,'banner');
assert.match(diagramView('consentdiff',consent).status,/1-step/);
console.log('Verified all six diagram state machines, alternate paths, calculation, and reset behavior.');
